/** 最小 session 日志（纯 JSONL），header 可配 delegationDepth。 */
const sessionJsonl = (depth: number, extra = ''): string =>
  `{"type":"session","version":0,"id":"s","createdAt":1,"cwd":"/x","delegationDepth":${depth}}\n${extra}`

describe('buildOverlayYaml', () => {
  it('overrides session-persistence-jsonl row with isolated root (leaving default zstd compression)', () => {
    const yaml = buildOverlayYaml('/tmp/eval-out/.sessions')
    expect(yaml).toBe(
      [
        '# generated by dsh-eval-harness eval_run — overlay for --patch (highest layer priority)',
        '- id: session-persistence-jsonl',
        "  name: '@deepseek-ai/dsh-session-persistence-jsonl'",
        '  config:',
        '    root: "/tmp/eval-out/.sessions"',
        '',
      ].join('\n'),
    )
  })

  it('does not force compression: none (v0.2 reads default multi-frame zstd directly)', () => {
    expect(buildOverlayYaml('/tmp/x')).not.toContain('compression:')
  })

  it('quotes the @-containing package name (YAML @ is a reserved indicator)', () => {
    expect(buildOverlayYaml('/tmp/x')).toContain("name: '@deepseek-ai/dsh-session-persistence-jsonl'")
  })

  it('escapes roots containing quotes/backslashes as a double-quoted YAML scalar', () => {
    const yaml = buildOverlayYaml('/tmp/we"ird\\root')
    expect(yaml).toContain('root: "/tmp/we\\"ird\\\\root"')
  })
})

describe('splitDshBin', () => {
  it('plain executable has no prefix args', () => {
    expect(splitDshBin('dsh')).toEqual({ bin: 'dsh', prefixArgs: [] })
  })
  it('splits npx-style commands into bin + prefix args', () => {
    expect(splitDshBin('npx -y @deepseek-ai/dsh')).toEqual({
      bin: 'npx',
      prefixArgs: ['-y', '@deepseek-ai/dsh'],
    })
  })
  it('tolerates extra whitespace', () => {
    expect(splitDshBin('  npx   -y   @deepseek-ai/dsh ')).toEqual({
      bin: 'npx',
      prefixArgs: ['-y', '@deepseek-ai/dsh'],
    })
  })
  it('throws eval_run: prefixed error on empty input', () => {
    expect(() => splitDshBin('   ')).toThrow(/^eval_run: dsh_bin is empty$/)
  })
})

