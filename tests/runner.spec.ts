/** 最小 session 日志（纯 JSONL），header 可配 delegationDepth。 */
const sessionJsonl = (depth: number, extra = ''): string =>
  `{"type":"session","version":0,"id":"s","createdAt":1,"cwd":"/x","delegationDepth":${depth}}\n${extra}`

