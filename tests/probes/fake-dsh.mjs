#!/usr/bin/env node
// 探针 agent（伪造 dsh，不解题）：按 dsh 命令行协议落一份 session 日志，用来检验判分
// 会不会被不解题的 agent 骗过。不连任何真实 LLM（relay 模式只连 eval_run 为本用例起的
// 127.0.0.1 mock），不执行 prompt 里的任何命令，只写 overlay 指定的 session 根，不碰真实
// ~/.dsh。底稿：docs/EVAL-HARDENING-DESIGN.md 附录 A。
//
// 模式（环境变量 PROBE_MODE，缺省或取值不认识时 exit 2，不静默退化成某个模式）：
//   do-nothing : 不调工具、空回复、turn_end=completed、exit 0
//   parrot     : 按 prompt 中「<name> 工具」字样依序调用（去重），参数为整段 prompt，
//                工具结果一律报错；最终回复 = 复述 prompt
//   relay      : 只用于 mock 用例：读隔离 $DSH_HOME/settings.yaml（必须是 eval_run 生成、
//                baseURL 指向 127.0.0.1、api 为 openai-completions，否则 exit 2），向 mock 发
//                流式请求，按 dsh 0.1.7-rc.2 的可观测行为转述——finish_reason=stop → 正文进
//                assistant/message、completed、exit 0；length → max-tokens、exit 1；断流或缺
//                终止证人 → 重试，共 3 次仍不行 → turn_end=error、exit 1（stderr 带
//                TRANSPORT: terminated）。供哨兵单测用：S1 必过、S2 必不过
//
// 协议：`--version` 打印探针版本；正常调用为 `--profile <p> --patch <overlay> <prompt>`
// （src/runner.ts 的 buildDshArgs）。
// 用法：runEval({ dshBin: `${process.execPath} <本文件绝对路径>` })——splitDshBin 按空白
// 拆分，经 node 启动不依赖文件可执行位。

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const MODES = ['do-nothing', 'parrot', 'relay']

function fail(message) {
  process.stderr.write(`fake-dsh: ${message}\n`)
  process.exit(2)
}

const argv = process.argv.slice(2)
if (argv[0] === '--version') {
  console.log('0.0.0-probe')
  process.exit(0)
}
const mode = process.env.PROBE_MODE
if (!MODES.includes(mode)) fail(`PROBE_MODE must be one of ${MODES.join(' | ')}, got '${mode ?? ''}'`)

// launcher flags 在前（--profile / --patch 各带一个值），第一个其它 token 即 prompt
let overlay
let prompt
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--profile') i++
  else if (argv[i] === '--patch') overlay = argv[++i]
  else {
    prompt = argv[i]
    break
  }
}
if (overlay === undefined) fail('missing --patch <overlay>')
if (prompt === undefined) fail('missing <prompt>')

// overlay 的 root 是 JSON 转义的 YAML 双引号标量（src/runner.ts 的 buildOverlayYaml）
const rootMatch = /^\s+root: (".*")$/m.exec(readFileSync(overlay, 'utf8'))
if (!rootMatch) fail(`no session root in overlay '${overlay}'`)
const dir = join(JSON.parse(rootMatch[1]), 'case', 'session-probe')
mkdirSync(dir, { recursive: true })

/** relay 的单次流式请求：拼正文、记 finish_reason；断流（FIN 让 chunked 流没收尾）返回 finish=null */
async function streamOnce(url, userPrompt) {
  let text = ''
  let finish = null
  try {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ model: 'mock-model', stream: true, messages: [{ role: 'user', content: userPrompt }] }),
    })
    const decoder = new TextDecoder()
    let buffer = ''
    for await (const chunk of res.body) {
      buffer += decoder.decode(chunk, { stream: true })
      for (let cut = buffer.indexOf('\n\n'); cut >= 0; cut = buffer.indexOf('\n\n')) {
        const data = /^data: (.*)$/m.exec(buffer.slice(0, cut))?.[1]
        buffer = buffer.slice(cut + 2)
        if (data === undefined || data === '[DONE]') continue
        const choice = JSON.parse(data).choices?.[0]
        text += choice?.delta?.content ?? ''
        if (choice?.finish_reason) finish = choice.finish_reason
      }
    }
  } catch {
    return { text: '', finish: null }
  }
  return { text, finish }
}

/** relay 模式：只接受 eval_run 生成、指向 127.0.0.1 的 mock settings（防止误连真实 provider） */
async function relayToMock(userPrompt) {
  const home = process.env.DSH_HOME
  if (!home) fail('relay mode needs the isolated DSH_HOME of a mock case')
  const settings = readFileSync(join(home, 'settings.yaml'), 'utf8')
  const baseURL = /^ *baseURL: (\S+)$/m.exec(settings)?.[1]
  const api = /^ *api: (\S+)$/m.exec(settings)?.[1]
  if (!settings.startsWith('# generated by dsh-eval-harness eval_run mock mode') || !baseURL?.startsWith('http://127.0.0.1:')) {
    fail(`relay mode only talks to the eval_run mock on 127.0.0.1, got settings '${join(home, 'settings.yaml')}'`)
  }
  if (api !== 'openai-completions') fail(`relay mode supports mock.api openai-completions only, got '${api ?? ''}'`)
  for (let attempt = 1; attempt <= 3; attempt++) {
    const { text, finish } = await streamOnce(`${baseURL}/chat/completions`, userPrompt)
    if (finish === 'stop') return { text, turnEnd: 'completed', exit: 0 }
    if (finish === 'length') return { text, turnEnd: 'max-tokens', exit: 1 }
  }
  return { text: '', turnEnd: 'error', exit: 1 }
}

const frames = [{ type: 'session', version: 0, id: 's', createdAt: 1, cwd: '/x', delegationDepth: 0 }]
let seq = 0
const ev = (type, data) => frames.push({ type, seq: ++seq, time: 1, data })
let step = 0
let finalText = ''
let turnEnd = 'completed'
let exitCode = 0
if (mode === 'relay') {
  const relayed = await relayToMock(prompt)
  finalText = relayed.text
  turnEnd = relayed.turnEnd
  exitCode = relayed.exit
}
if (mode === 'parrot') {
  const tools = [...new Set([...prompt.matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*工具/g)].map((m) => m[1]))]
  for (const name of tools) {
    step++
    const callId = `c${step}`
    ev('tool/call', { turn: 1, step, callId, name, arguments: JSON.stringify({ input: prompt }) })
    // 真实落盘形状：结果在 message.content[] 的 tool-result 块里，isError=true
    ev('tool/result', {
      turn: 1,
      step,
      message: {
        source: { kind: 'tool', callId },
        content: [{ type: 'tool-result', toolCallId: callId, content: [{ type: 'text', text: 'simulated: invalid arguments' }], isError: true }],
        role: 'user',
        id: `r${step}`,
      },
    })
    ev('step/end', { turn: 1, step })
  }
  finalText = prompt
}
step++
ev('assistant/message', { turn: 1, step, message: { role: 'assistant', content: [{ type: 'text', text: finalText }] } })
ev('step/end', { turn: 1, step })
ev('turn/end', { turn: 1, reason: { kind: turnEnd } })
writeFileSync(join(dir, 'session.jsonl'), `${frames.map((f) => JSON.stringify(f)).join('\n')}\n`)
if (turnEnd === 'error') process.stderr.write('fake-dsh: TRANSPORT: terminated\n')
process.exit(exitCode)
